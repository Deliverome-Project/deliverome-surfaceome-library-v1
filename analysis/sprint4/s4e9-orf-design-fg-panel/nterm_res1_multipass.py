def planned_leader(out: pd.DataFrame) -> pd.DataFrame:
    """One row per member: the planned leader and who decided it.

    GPCRs take GPCR_LEADER. A non-GPCR takes the verdict from NONGPCR_REVIEW
    (`igk` / `leader_free` / `off_rung` / `hold`). That verdict is a recommendation for
    Becca to confirm, so its decided_by says so. A non-GPCR with no review row is left
    blank rather than defaulted.
    """
    # Keyed on design_id: candidate_id is renumbered by #272 and #283, design_id is not.
    review = pd.read_csv(NONGPCR_REVIEW, sep="\t", dtype=str).set_index("design_id")
    rows = []
    for r in out[["candidate_id", "design_id", "gpcr"]].itertuples():
        if r.gpcr == 1:
            rows.append({"candidate_id": r.candidate_id, **GPCR_LEADER})
        elif r.design_id in review.index:
            v = review.loc[r.design_id]
            rows.append(
                {
                    "candidate_id": r.candidate_id,
                    "planned_leader": v["verdict"],
                    "planned_leader_decided_by": (
                        'l1-nterm-res1-multipass (delegated by Becca 2026-11-12, "use your best judgment")'
                    ),
                    "planned_leader_implemented_by": IMPLEMENTED_BY,
                    "planned_leader_reason": f"{v['confidence']} confidence: {v['reason']}",
                }
            )
        else:
            rows.append({"candidate_id": r.candidate_id})
    return pd.DataFrame(rows)


def subgroup(x: pd.Series) -> str:
    """Which question the leader decision turns on for this member. First match wins.

    UniProt features count only when the member starts where the canonical does.

    1. The N-terminus may not be extracellular at all: a non-GPCR whose UniProt entry calls
       its first topological domain cytoplasmic. A leader would force the predicted
       orientation, so it would invert such a protein rather than rescue it. GPCRs are
       exempt: an extracellular N-terminus is class-level and Tedman displayed HA there.
    2. Residue 1 may start a signal peptide (UniProt or v2 calls one), so a tag placed
       there could be cleaved off, and a leader in front would turn the native signal into
       an internal hydrophobic segment.
    3. The native tail is shorter than the 15-residue flank, so the cassette's charges enter
       TM1's N-flank and leave Hartmann's charge difference at or below zero.
    4. The tail is long enough that the tagged tail exceeds what Tedman shows displaying.
    """
    same = x["uniprot_same_start"] == 1
    if same and not x["gpcr"] and x["uniprot_n_terminus"] == "Cytoplasmic":
        return SUB_ORIENTATION
    v2_sp = pd.to_numeric(x["v2_signal_peptide_aa"], errors="coerce")
    up_sp = pd.to_numeric(x["uniprot_signal_end"], errors="coerce")
    if (v2_sp > 0) or (same and up_sp > 0):
        return SUB_SIGNAL
    if x["n_tail_aa"] < FLANK and x["delta_charge_tagged"] <= 0 < x["delta_charge_native"]:
        return SUB_SHORT
    if x["n_tail_aa"] >= LONG_TAIL:
        return SUB_LONG
    return SUB_DEFAULT


def check_drift() -> int:
    """List members whose recorded inputs no longer match, without rerunning anything.

    Compares, per member of the current rung: the designed sequence hash and the pinned
    DeepTMHMM v1 `topology_version` against the table, and the UniProt entry and sequence
    versions against a fresh fetch of only those two fields. A rung whose membership changed
    (e.g. a new ortholog panel) is reported too. Any change means rerun with `--refresh`.
    """
    table = pd.read_csv(OUT, sep="\t", dtype=str).fillna("")
    paths = pd.read_csv(TAG_PATHS, sep="\t", dtype=str)
    rung = paths[paths["placement"] == RUNG]
    drift: list[str] = []
    added = set(rung["candidate_id"]) - set(table["candidate_id"])
    removed = set(table["candidate_id"]) - set(rung["candidate_id"])
    if added or removed:
        drift.append(f"rung membership: +{len(added)} -{len(removed)}")

    members = ld.designed_proteins(MANIFEST, library=ld.LIBRARY_L1)
    keep = {c: members[c] for c in rung["candidate_id"] if c in members}
    v1 = ld.topology_report(keep, tool=topology.TOOL_V1).set_index("candidate_id")
    for r in table.itertuples():
        if r.candidate_id not in v1.index:
            continue
        now = v1.loc[r.candidate_id]
        if now["sequence_sha256"] != r.sequence_sha256:
            drift.append(f"{r.candidate_id} {r.gene_symbol}: designed sequence changed")
        elif str(now["topology_version"]) != r.topology_version:
            drift.append(
                f"{r.candidate_id} {r.gene_symbol}: deeptmhmm_v1 topology_version "
                f"{r.topology_version} -> {now['topology_version']}"
            )

    accs = sorted({a for a in table["uniprot_accession"] if a})
    current: dict[str, tuple[str, str]] = {}
    release = ""
    for i in range(0, len(accs), 100):
        q = urllib.parse.quote(" OR ".join(f"accession:{a}" for a in accs[i : i + 100]))
        text, release, _ = _fetch(
            "https://rest.uniprot.org/uniprotkb/search?format=tsv&size=500"
            f"&fields=accession,version,sequence_version&query={q}"
        )
        for row in pd.read_csv(io.StringIO(text), sep="\t", dtype=str).itertuples(index=False):
            current[row[0]] = (row[1], row[2])
    for r in table[table["uniprot_accession"] != ""].itertuples():
        was = (r.uniprot_entry_version, r.uniprot_sequence_version)
        now = current.get(r.uniprot_accession)
        if now is None:
            drift.append(f"{r.candidate_id} {r.gene_symbol}: {r.uniprot_accession} not found")
        elif now[1] != was[1]:
            drift.append(
                f"{r.candidate_id} {r.gene_symbol}: UniProt sequence version {was[1]} -> {now[1]}"
            )
        elif now[0] != was[0]:
            drift.append(
                f"{r.candidate_id} {r.gene_symbol}: UniProt entry version {was[0]} -> {now[0]}"
            )
    print(f"recorded UniProt release {_release()}; current {release}")
    print(f"{len(drift)} input change(s)")
    for d in drift:
        print("  " + d)
    return 1 if drift else 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--refresh", action="store_true", help="re-fetch both UniProt snapshots")
    ap.add_argument(
        "--check-drift",
        action="store_true",
        help="compare the recorded input fingerprints with today's; exit 1 if any moved",
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="rebuild from the snapshots and compare with the committed table; write nothing",
    )
    args = ap.parse_args(argv)
    if args.check and args.refresh:
        raise SystemExit("--check runs from the committed snapshots; drop --refresh")
    if args.check_drift:
        return check_drift()

    paths = pd.read_csv(TAG_PATHS, sep="\t")
    rung = paths[paths["placement"] == RUNG].copy()
    print(f"{RUNG}: {len(rung)} members (l1_tag_paths.tsv)")

    # Tedman: strip the _ENST suffix, keep the receptor's class and intensity.
    ted = pd.read_excel(external.download(SCREEN), sheet_name="Canonical")
    ted["tedman_symbol"] = ted["Receptor Name"].str.replace(r"_ENST\d+.*$", "", regex=True)
    ted = ted.rename(
        columns={"GPCR Class": "tedman_class", "Immunostaining Intensity": "tedman_au"}
    )[["tedman_symbol", "tedman_class", "tedman_au"]]
    uni = _uniprot_gpcrs(args.refresh)

    feats = _uniprot_features(sorted(set(rung["gene_symbol"])), args.refresh)
    ens = _ensembl(
        list(rung["gene_symbol"])
        + list(ted["tedman_symbol"])
        + list(uni["gene_primary"])
        + list(feats["gene_primary"])
    )
    feat_by_ens: dict[str, dict] = {}
    for r in feats.to_dict("records"):
        for e in ens.get(r["gene_primary"], ()):
            feat_by_ens.setdefault(e, r)
    ted_by_ens: dict[str, dict] = {}
    for r in ted.to_dict("records"):
        for e in ens.get(r["tedman_symbol"], ()):
            ted_by_ens.setdefault(e, r)
    uni_by_ens: dict[str, str] = {}
    for r in uni.to_dict("records"):
        for e in ens.get(r["gene_primary"], ()):
            uni_by_ens.setdefault(e, r["accession"])

    # v1 and v2 strings for each member's own ordered sequence.
    members = ld.designed_proteins(MANIFEST, library=ld.LIBRARY_L1)
    members = {cid: members[cid] for cid in rung["candidate_id"]}
    v1 = ld.topology_report(members, tool=topology.TOOL_V1).set_index("candidate_id")
    v2 = ld.topology_report(members, tool=topology.TOOL_V2).set_index("candidate_id")

    rows = []
    for r in rung.to_dict("records"):
        cid = r["candidate_id"]
        seq = members[cid]["sequence"].rstrip("*")
        topo = v1.at[cid, "per_residue_topology"]
        if topology.sequence_sha256(seq) != r["sequence_sha256"]:
            raise SystemExit(f"{cid}: designed sequence no longer matches l1_tag_paths.tsv")
        gene_ens = ens.get(r["gene_symbol"], set())
        t = next((ted_by_ens[e] for e in sorted(gene_ens) if e in ted_by_ens), None)
        acc = next((uni_by_ens[e] for e in sorted(gene_ens) if e in uni_by_ens), None)
        v2_topo = v2.at[cid, "dtm2_topology_string"] if bool(v2.at[cid, "found"]) else None
        f = next((feat_by_ens[e] for e in sorted(gene_ens) if e in feat_by_ens), None)
        side, evidence = _first_topo(f["ft_topo_dom"]) if f else ("", "")
        # UniProt's N-terminal features describe the canonical's first residues, so they
        # apply to this member only when it starts the same way. An isoform that starts
        # downstream (PTCH1 l1-m2641 begins at canonical residue 152, after TM1) has a
        # different N-terminus and its canonical's annotation says nothing about it.
        same_start = bool(f) and f["sequence"].startswith(seq[:N_START])
        rows.append(
            {
                "candidate_id": cid,
                "candidate_set": r["candidate_set"],
                "species": r["species"],
                "gene_symbol": r["gene_symbol"],
                "ensembl_gene": ";".join(sorted(gene_ens)),
                "in_tedman": int(t is not None),
                "tedman_class": t["tedman_class"] if t else "",
                "tedman_au": round(float(t["tedman_au"]), 1) if t else "",
                "uniprot_kw0297": acc or "",
                "gpcr": int(t is not None or acc is not None),
                "n_tm": r["n_tm"],
                "length_aa": r["length_aa"],
                **tm1_features(seq, topo),
                "v2_found": int(v2_topo is not None),
                # Only v2's signal-peptide call is read: its other state letters are not
                # documented in this repo, so its membrane side is not decoded here.
                "v2_signal_peptide_aa": (len(v2_topo) - len(v2_topo.lstrip("S")))
                if v2_topo
                else "",
                "uniprot_accession": f["accession"] if f else "",
                "uniprot_release": _release() if f else "",
                "uniprot_entry_version": f.get("entry_version", "") if f else "",
                "uniprot_sequence_version": f.get("sequence_version", "") if f else "",
                "uniprot_same_start": int(same_start),
                "uniprot_signal_end": _signal_end(f["ft_signal"]) if f else "",
                "uniprot_n_terminus": side,
                "uniprot_n_terminus_evidence": evidence,
                "topology_version": r["topology_version"],
                "sequence_sha256": r["sequence_sha256"],
            }
        )
    out = pd.DataFrame(rows)
    # `design_id` is stable across member renumbering (`candidate_id` is not: #272 and the
    # ortholog adoption in #283 each renumbered it), so it goes first as the join key.
    design = pd.read_csv(MANIFEST, sep="\t", dtype=str).set_index("candidate_id")["design_id"]
    out.insert(0, "design_id", out["candidate_id"].map(design))
    if out["design_id"].isna().any():
        raise SystemExit("members without a design_id in the manifest")
    out["group"] = out.apply(
        lambda x: (
            "GPCR, in Tedman screen"
            if x["in_tedman"]
            else ("GPCR, not in screen" if x["gpcr"] else "not a GPCR")
        ),
        axis=1,
    )
    out["leader_subgroup"] = out.apply(subgroup, axis=1)
    out["leader_subgroup_decided_by"] = DECIDED_BY
    out["leader_subgroup_implemented_by"] = IMPLEMENTED_BY
    out["leader_subgroup_reason"] = out["leader_subgroup"].map(SUB_REASON)
    out = out.merge(planned_leader(out), on="candidate_id", how="left", validate="1:1")
    # Cassette: the full 51-aa tandem, leading GGGGS kept. Decided by Becca on 2026-11-11
    # ("keep full"); tested and implemented by the session l1-nterm-type3 (PR #282). Without
    # the spacer, DeepTMHMM v1 called a cleavable signal peptide ending inside SpyTag003 on
    # 12 of 62 residue-1 tag-alone arms, and on 0 of 62 with it.
    out["cassette"] = f"full {len(CASSETTE_AA)} aa, leading GGGGS kept"
    out["cassette_decided_by"] = 'Becca, 2026-11-11 ("keep full")'
    out["cassette_implemented_by"] = "Claude Code session l1-nterm-type3, PR #282"
    out["cassette_reason"] = (
        "without the leading GGGGS, v1 called a signal peptide ending inside SpyTag003 on "
        "12 of 62 residue-1 tag-alone arms; 0 of 62 with it"
    )
    text = out.to_csv(sep="\t", index=False, lineterminator="\n")
    if args.check:
        same = OUT.read_text() == text
        print(
            f"{OUT.name}: " + ("record matches rebuild" if same else "record DIFFERS from rebuild")
        )
        return 0 if same else 1
    OUT.write_text(text)
    print(f"wrote {OUT.name}: {len(out)} rows")
    print(f"leader {len(LEADER_AA)} aa + Asp; cassette {len(CASSETTE_AA)} aa")

    sets = ["library_reference", "isoform", "ortholog"]
    tab = pd.crosstab(out["group"], out["candidate_set"]).reindex(columns=sets, fill_value=0)
    tab["total"] = tab.sum(axis=1)
    print("\n" + tab.to_string())
    print(
        "\nGPCRs not in the screen:",
        sorted(out.query("group == 'GPCR, not in screen'")["gene_symbol"]),
    )
    non = out[out["gpcr"] == 0]
    print(f"\nnon-GPCRs ({len(non)}):", " ".join(sorted(non["gene_symbol"])))

    for name, df in (("GPCR", out[out["gpcr"] == 1]), ("non-GPCR", non)):
        q = df["n_tail_aa"].quantile([0, 0.25, 0.5, 0.75, 1]).round().astype(int).tolist()
        print(
            f"\n{name}: N-tail aa min/q1/median/q3/max {q}; "
            f"native delta<=0 {int((df['delta_charge_native'] <= 0).sum())}; "
            f"tagged delta<=0 {int((df['delta_charge_tagged'] <= 0).sum())}; "
            f"v2 SP {int((pd.to_numeric(df['v2_signal_peptide_aa'], errors='coerce').fillna(0) > 0).sum())}"
            f" of {int(df['v2_found'].sum())} with v2"
        )

    # Does a longer leaderless N-tail predict less surface signal in Tedman's screen, where
    # every class A / olfactory receptor carried HA after Met1 and no leader? One row per
    # gene, library references only, so the tail measured is the gene's reference form.
    g = out[(out["in_tedman"] == 1) & (out["candidate_set"] == "library_reference")]
    g = g.drop_duplicates("gene_symbol")
    g = g.assign(tedman_au=pd.to_numeric(g["tedman_au"]), n_tail_aa=g["n_tail_aa"].astype(int))
    print(f"\nTedman intensity vs N-tail length, one row per gene (n={len(g)}), Spearman:")
    for cls, df in [("all", g), *sorted(g.groupby("tedman_class"))]:
        if len(df) >= 10:
            rho, p = spearmanr(df["n_tail_aa"], df["tedman_au"])
            print(f"  {cls:16s} n={len(df):>3}  rho={rho:+.2f}  p={p:.1e}")
    bins = pd.cut(g["n_tail_aa"], [0, 20, 30, 45, 70, 100, 1000])
    print(g.groupby(bins, observed=True)["tedman_au"].agg(["count", "median"]).round(0))

    print("\nleader subgroups (members):")
    sub = pd.crosstab(out["leader_subgroup"], out["gpcr"].map({1: "GPCR", 0: "non-GPCR"}))
    sub["total"] = sub.sum(axis=1)
    print(sub.to_string())
    for name, df in out[out["leader_subgroup"] != SUB_DEFAULT].groupby("leader_subgroup"):
        print(f"\n{name}:")
        print(
            "  "
            + ", ".join(
                f"{r.gene_symbol} ({r.candidate_id}, {r.candidate_set[:3]}, tail {r.n_tail_aa})"
                for r in df.sort_values("n_tail_aa", ascending=False).itertuples()
            )
        )
    return 0


