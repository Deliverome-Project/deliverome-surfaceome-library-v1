def _fetch(url: str) -> tuple[str, str, str]:
    """(body, UniProt release, release date) for one REST call."""
    with urllib.request.urlopen(url, timeout=120) as fh:
        return (
            fh.read().decode(),
            fh.headers.get("X-UniProt-Release", ""),
            fh.headers.get("X-UniProt-Release-Date", ""),
        )


def _record_release(release: str, release_date: str) -> None:
    """Write the release the snapshots came from; refuse to mix two releases."""
    meta = json.loads(UNIPROT_META.read_text()) if UNIPROT_META.exists() else {}
    if meta.get("release") not in (None, release) and meta.get("fetched") == str(date.today()):
        raise SystemExit(f"UniProt release changed mid-refresh: {meta['release']} -> {release}")
    UNIPROT_META.write_text(
        json.dumps(
            {"release": release, "release_date": release_date, "fetched": str(date.today())},
            indent=2,
        )
        + "\n"
    )


def _release() -> str:
    return json.loads(UNIPROT_META.read_text())["release"] if UNIPROT_META.exists() else ""


def _uniprot_gpcrs(refresh: bool) -> pd.DataFrame:
    if refresh or not UNIPROT_SNAPSHOT.exists():
        text, release, rdate = _fetch(UNIPROT_URL)
        _record_release(release, rdate)
        df = pd.read_csv(io.StringIO(text), sep="\t").rename(
            columns={"Entry": "accession", "Gene Names (primary)": "gene_primary"}
        )
        df = df.dropna(subset=["gene_primary"]).sort_values("accession")
        df.to_csv(UNIPROT_SNAPSHOT, sep="\t", index=False)
    return pd.read_csv(UNIPROT_SNAPSHOT, sep="\t")


def _uniprot_features(genes: list[str], refresh: bool) -> pd.DataFrame:
    if refresh or not UNIPROT_FEATURES.exists():
        frames = []
        for i in range(0, len(genes), 40):
            chunk = " OR ".join(f"gene_exact:{g}" for g in genes[i : i + 40])
            q = urllib.parse.quote(f"({chunk}) AND organism_id:9606 AND reviewed:true")
            text, release, rdate = _fetch(UNIPROT_SEARCH + q)
            _record_release(release, rdate)
            frames.append(pd.read_csv(io.StringIO(text), sep="\t"))
        df = pd.concat(frames).rename(
            columns={
                "Entry": "accession",
                "Gene Names (primary)": "gene_primary",
                "Signal peptide": "ft_signal",
                "Topological domain": "ft_topo_dom",
                "Sequence": "sequence",
                "Entry version": "entry_version",
                "Sequence version": "sequence_version",
            }
        )
        df = df.dropna(subset=["gene_primary"]).drop_duplicates("accession")
        df.sort_values("accession").to_csv(UNIPROT_FEATURES, sep="\t", index=False)
    return pd.read_csv(UNIPROT_FEATURES, sep="\t", dtype=str).fillna("")


def _first_topo(ft: str) -> tuple[str, str]:
    """(side, evidence) of the first topological domain, e.g. ("Cytoplasmic", "experimental").

    ECO:0000269 is experimental evidence; anything else (sequence analysis 0000255, by
    similarity 0000250, curator inference 0000305) is recorded as "inferred".
    """
    m = re.search(r'TOPO_DOM (\d+)\.\.\d+; /note="([^"]+)"; /evidence="([^"]+)"', ft)
    if not m:
        return "", ""
    return m.group(2), ("experimental" if "ECO:0000269" in m.group(3) else "inferred")


def _signal_end(ft: str) -> int:
    m = re.search(r"SIGNAL 1\.\.(\d+)", ft)
    return int(m.group(1)) if m else 0


def _ensembl(symbols) -> dict[str, set[str]]:
    return {s: set(ids) for s, ids in gene_resolver.to_ensembl(sorted(set(symbols))).items()}


def _segments(topo: str) -> list[tuple[str, int, int]]:
    """(state, start, end) runs, 0-based half-open."""
    out, start = [], 0
    for i in range(1, len(topo) + 1):
        if i == len(topo) or topo[i] != topo[start]:
            out.append((topo[start], start, i))
            start = i
    return out


def _charge(seq: str) -> tuple[int, int]:
    return sum(c in POSITIVE for c in seq), sum(c in NEGATIVE for c in seq)


def tm1_features(seq: str, topo: str) -> dict:
    """What sits either side of the first helix, before and after the cassette goes in.

    The cassette goes after Met1, so it lengthens the N-tail (the segment TM1 must translocate
    post-insertion when there is no leader) and adds its own charge to it. The 15-residue
    flank next to TM1 changes only when the native N-tail is shorter than the cassette's
    reach, i.e. shorter than 15 residues.
    """
    segs = _segments(topo)
    tm1 = next(s for s in segs if s[0] == "M")
    n_tail = seq[: tm1[1]]
    after = seq[tm1[2] : tm1[2] + FLANK]
    n_flank = n_tail[-FLANK:]
    pos_tail, neg_tail = _charge(n_tail)
    pos_c, _ = _charge(after)
    pos_n, _ = _charge(n_flank)
    # The tagged N-tail: Met1, cassette, then the rest of the native tail.
    tagged_tail = n_tail[:1] + CASSETTE_AA + n_tail[1:]
    tag_pos, tag_neg = _charge(tagged_tail)
    tagged_flank_pos, _ = _charge(tagged_tail[-FLANK:])
    return {
        "n_tail_aa": len(n_tail),
        "tm1_start": tm1[1] + 1,
        "tm1_end": tm1[2],
        "n_tail_pos": pos_tail,
        "n_tail_neg": neg_tail,
        "n_tail_net": pos_tail - neg_tail,
        "n_tail_sequons": len(SEQUON.findall(n_tail)),
        "tm1_c_flank_pos": pos_c,
        "tm1_n_flank_pos": pos_n,
        # Hartmann's charge difference: positive charges on the C side minus the N side.
        # Positive means the flanks agree with N-out/C-in, the orientation predicted.
        "delta_charge_native": pos_c - pos_n,
        "tagged_n_tail_aa": len(tagged_tail),
        "tagged_n_tail_net": tag_pos - tag_neg,
        "delta_charge_tagged": pos_c - tagged_flank_pos,
    }


