"""Who the "N at residue 1, multipass" members are, and what an N-terminal cassette does to TM1.

`l1_tag_paths.tsv` puts these members on the rung on the strength of Tedman's GPCR screen,
which tagged every leaderless class A / olfactory receptor with HA right after Met1 and still
read surface display. This script measures how far that evidence reaches across the rung and
what the 51-aa tandem changes for each member's first helix. It writes
`nterm_res1_multipass.tsv` (one row per member) and prints the summary tables in
`NTERM_RES1_MULTIPASS.md`.

**GPCR membership** comes from two sources, joined on Ensembl gene ID through
`gene_resolver` (never on a display symbol):

* Tedman's Canonical sheet, `Receptor Name` with its `_ENST...` suffix stripped. A member
  whose gene is there inherits that receptor's immunostaining intensity and class.
* UniProt keyword KW-0297 (G-protein coupled receptor), reviewed human entries. That catches
  receptors the screen did not include. The fetched list is snapshotted beside this script as
  `uniprot_kw0297_human.tsv`, so a re-run reproduces without the network; pass `--refresh` to
  fetch it again.

Orthologs carry the human gene symbol in the manifest, so they classify through their human
gene.

**TM1 features** come from each member's own DeepTMHMM v1 string, matched on the sha256 of its
ordered sequence by `library_design.topology_report`, exactly as `l1_tag_paths.py` does. v2 is
looked up alongside and only reported: a member whose v2 string does not also start
extracellular is one where the orientation a leader would enforce is less certain.

**Attribution** (Becca's rule, 2026-11-10: note the agent behind every manual fix and its
reasoning). Nothing here overrides a value or carries a hand-picked member list. GPCR status
is computed from the screen and KW-0297; there is no hand-added list of unscreened GPCRs.
The analysis choices are the constants FLANK, N_START and LONG_TAIL and the subgroup rules in
`subgroup()`. They were chosen by the Claude Code session l1-nterm-res1-multipass (branch
`claude/l1-nterm-res1-multipass-2cedd2`, PR #280), and no person has decided them. Each
constant's comment gives its reason. Every output row carries `leader_subgroup_decided_by`,
`leader_subgroup_implemented_by` and `leader_subgroup_reason`, so the attribution survives
when the table is read alone. Everything is regenerated by this script from the committed
UniProt snapshots, Tedman's sheet and the pinned topology snapshot.

**Reproducibility** (Becca, 2026-11-11: DeepTMHMM v1 by default, and pin every input so we
can tell when a rerun is needed). Topology is DeepTMHMM v1 (`topology.TOOL_V1`) in every call,
matched by sequence hash against the snapshot pinned in `topology.SNAPSHOT_KEY`. v2 is
consulted only for its signal-peptide call. The UniProt release and each entry's
`entryVersion` / `sequenceVersion` are snapshotted with the features, and the release is
recorded in `uniprot_nterm_res1_snapshot.json`. Every output row carries
`uniprot_release`, `uniprot_entry_version`, `uniprot_sequence_version`, `topology_version`
and `sequence_sha256`. `--check-drift` re-fetches only those fingerprints and lists the
members whose inputs changed; it exits 1 if any did, which is the signal to rerun with
`--refresh`.

    uv run --locked python nterm_res1_multipass.py                # offline, from snapshots
    uv run --locked python nterm_res1_multipass.py --check-drift  # has anything moved?
    uv run --locked python nterm_res1_multipass.py --refresh      # re-fetch UniProt, rerun
"""

