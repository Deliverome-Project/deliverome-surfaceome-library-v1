"""TFRC inter-tag linker arms: p003 as built, plus a 3x and a 4x GGGGS spacer.

Scope note (Becca, 2026-09-26, revised 2026-10-01): this began as a five-arm
placement/order study including SLC20A2 N- versus C-terminal arms, then became a
cassette-order swap. Both were dropped. What is built is a linker-length series.
**The N-versus-C placement question is therefore still open** — see the README.

Why linker length. S3E9 measures a 9-14% loss of ALFA signal when SpyCatcher is
co-bound on L-0004, rising with labelling time. Read as occupancy rather than as an
equilibrium constant, that is a 0.1-1.8 kcal/mol penalty depending on how saturating
the stain is — consistent with the two binders' excluded volumes overlapping on a
10-aa tether. Modelling the spacer as a worm-like chain and fitting the one free
parameter (the exclusion distance) against the measured penalty predicts the penalty
falls to 3-8% at 3x GGGGS and 2-4% at 4x, i.e. a 5-9 point recovery that is robust
across the whole plausible saturation range. The two arms are not expected to be
separable from *each other* (1.6-2.1 points, which needs n>125); each is separable
from the p003 reference (n=6-12 paired). Regenerated by linker_model.py.

Only the **inter-tag** spacer changes. The flanking GGGGS blocks either side of the
cassette are untouched, because the geometry under test is the distance between
SpyTag003 and ALFA, not the distance from either to the protein.

    cterm      …ORF | GGGGS SpyTag003 (GGGGS)x2 P-ALFA-P GGGGS |  p003, the reference
    linker_3x  …ORF | GGGGS SpyTag003 (GGGGS)x3 P-ALFA-P GGGGS |
    linker_4x  …ORF | GGGGS SpyTag003 (GGGGS)x4 P-ALFA-P GGGGS |

The added spacers are **not** more copies of the p003 GGGGS codons. Repeating
``GGAGGAGGAGGCAGC`` four times would put a 45-nt direct repeat in the construct (the
p003 cassette already carries a 17-nt one), which is a slippage and recombination
substrate. Each arm's spacer is drawn by ``seqtools.diversify_linker`` from a fixed
seed, so rebuilds are byte-identical while the longest internal repeat stays <= 9 nt.

Controls that make this a one-variable comparison:

* the ORF is lifted **verbatim** from the assembled p003 map (4831..7110 — already
  domesticated, 0 Type IIS sites);
* ``main`` asserts the ``cterm`` arm reproduces p003's coding region byte-for-byte,
  and that all three arms differ *only* in the inter-tag spacer;
* both tags are already validated in this order — ALFA distal by S2E9 (anti-ALFA
  nanobody on TfR1-Spy/ALFA, 51-73x over WT) and SpyTag proximal by S2E10
  (SpyCatcher-CF488A/CF647 on the same L-0004 line).

What it does not test: it moves both tags apart at once, so a difference cannot be
assigned to ALFA or to SpyTag individually. The order-of-addition control (label ALFA,
wash, then add SpyCatcher) separates kinetic competition from geometry and needs no
new construct.
"""

from __future__ import annotations

import argparse
import csv
import random
from pathlib import Path

from build_constructs import (
    CASSETTE,
    CASSETTE_AA,
    CS1,
    ENZYMES,
    FWD_PRIMER,
    KOZAK,
    REV_PRIMER,
    SPACER,
    STOP,
)

from deliverome_analysis import seqtools

HERE = Path(__file__).parent

# p003 cassette blocks, read off the assembled map (see build_constructs.CASSETTE).
L1 = "GGAGGAGGAGGCAGC"  # GGGGS
SPY = "AGAGGCGTGCCACACATCGTGATGGTGGATGCCTACAAGAGATACAAG"  # SpyTag003, RGVPHIVMVDAYKRYK
L2 = "GGAGGAGGCGGCTCTGGAGGAGGAGGCAGC"  # GGGGSGGGGS, the inter-tag spacer
P1 = "CCC"  # P
ALFA = "AGTCGCCTCGAAGAAGAGCTCAGGCGGAGACTGACAGAG"  # ALFA v1.5, SRLEEELRRRLTE
P2 = "CCT"  # P
L3 = "GGAGGAGGAGGCAGC"  # GGGGS

# Seeded so a rebuild reproduces the ordered sequence exactly. Changing this reseeds
# every arm's spacer, which would invalidate anything already synthesised.
SPACER_SEED = 20261001

# The ORF exactly as it sits in the assembled p003 map: already domesticated, and
# carrying NO stop codon — the cassette supplies it. Saved out of the GenBank because
# that map is local-only (same gap flagged in s1e2/enzyme_scan.py).
TFRC_ORF_FILE = HERE / "tfrc_p003_orf.txt"


def build_spacer(repeats: int, rng: random.Random) -> str:
    """A fresh, low-repeat encoding of ``repeats`` x GGGGS for the inter-tag spacer.

    Flanked by the real neighbours so a Type IIS site cannot be created across either
    junction, and held to a longest internal direct repeat of 9 nt.
    """
    return seqtools.diversify_linker(
        "GGGGS" * repeats,
        flank5=SPY,
        flank3=P1 + ALFA,
        enzymes=ENZYMES,
        gc_min=0.45,
        gc_max=0.70,
        label=f"inter-tag {repeats}x GGGGS",
        rng=rng,
    ).sequence


def cassette_for(spacer: str) -> tuple[str, str]:
    """Assemble the cassette around an inter-tag ``spacer``; return (dna, protein)."""
    dna = L1 + SPY + spacer + P1 + ALFA + P2 + L3
    return dna, seqtools.translate(dna)


def arms() -> dict[str, tuple[str, str, str]]:
    rng = random.Random(SPACER_SEED)
    out = {"cterm": (CASSETTE, CASSETTE_AA, "p003 cassette verbatim — the matched reference")}
    for repeats in (3, 4):
        dna, aa = cassette_for(build_spacer(repeats, rng))
        out[f"linker_{repeats}x"] = (
            dna,
            aa,
            f"inter-tag spacer lengthened to {repeats}x GGGGS ({repeats * 5} aa)",
        )
    return out


def build(arm: str, spec: tuple[str, str, str], orf: str, barcode: str) -> dict:
    cassette, cassette_aa, note = spec
    coding = orf + cassette
    protein = seqtools.translate(coding + STOP)
    if protein.rstrip("*") != seqtools.translate(orf) + cassette_aa:
        raise RuntimeError(f"{arm}: assembled protein is not the intended fusion")
    insert = KOZAK + coding + STOP + SPACER + FWD_PRIMER + barcode + REV_PRIMER + CS1
    sites = seqtools.find_sites(insert, ENZYMES)
    if sites:
        raise RuntimeError(f"{arm}: created Type IIS site(s): {sites}")
    spacer_aa = cassette_aa[len(seqtools.translate(L1 + SPY)) :].split("P")[0]
    return {
        "gene": "TFRC",
        "arm": arm,
        "note": note,
        "inter_tag_spacer_aa": len(spacer_aa),
        "inter_tag_repeats": len(spacer_aa) // 5,
        "max_internal_repeat_nt": seqtools.max_internal_repeat(cassette),
        "insert_after_residue": len(orf) // 3,
        "protein_aa": len(protein) - 1,
        "insert_nt": len(insert),
        "barcode": barcode,
        "insert": insert,
        "cassette": cassette,
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=HERE)
    parser.add_argument(
        "--barcodes",
        type=Path,
        default=HERE / "barcodes_tfrc.tsv",
        help="arm -> barcode table; every arm must have a reserved barcode",
    )
    args = parser.parse_args(argv)

    spec = arms()
    orf = TFRC_ORF_FILE.read_text().strip()
    barcodes = {
        r["arm"]: r["barcode"] for r in csv.DictReader(args.barcodes.open(), delimiter="\t")
    }
    missing = [a for a in spec if not barcodes.get(a)]
    if missing:
        raise SystemExit(
            f"no reserved barcode for {missing}. Draw one with reserve_barcodes.py (reads "
            f"the s1e2 pool from S3), then register it with append_reservations.py. Do not "
            f"invent a barcode here — the pool index is what keeps the registry consistent."
        )

    rows = [build(a, spec[a], orf, barcodes[a]) for a in spec]

    if not rows[0]["insert"].startswith(KOZAK + orf + CASSETTE + STOP):
        raise RuntimeError("cterm arm does not reproduce the p003 coding region")
    print("cterm arm reproduces the p003 coding region byte-for-byte ✓")
    head, tail = L1 + SPY, P1 + ALFA + P2 + L3
    for r in rows:
        if not (r["cassette"].startswith(head) and r["cassette"].endswith(tail)):
            raise RuntimeError(f"{r['arm']}: changed something other than the inter-tag spacer")
    print("all arms differ only in the inter-tag spacer ✓\n")

    for r in rows:
        print(
            f"TFRC.{r['arm']:10s} spacer {r['inter_tag_repeats']}x "
            f"({r['inter_tag_spacer_aa']:2d} aa)  protein {r['protein_aa']:4d} aa  "
            f"insert {r['insert_nt']:5d} nt  longest repeat {r['max_internal_repeat_nt']:2d} nt  "
            f"bc={r['barcode']}"
        )

    cols = [
        "gene",
        "arm",
        "note",
        "inter_tag_spacer_aa",
        "inter_tag_repeats",
        "max_internal_repeat_nt",
        "insert_after_residue",
        "protein_aa",
        "insert_nt",
        "barcode",
    ]
    table = args.out_dir / "constructs_tag_arms.tsv"
    with table.open("w", newline="") as h:
        w = csv.DictWriter(
            h, fieldnames=cols, delimiter="\t", extrasaction="ignore", lineterminator="\n"
        )
        w.writeheader()
        w.writerows(rows)
    fasta = args.out_dir / "constructs_tag_arms.fasta"
    fasta.write_text(
        "".join(
            f">{r['gene']}_{r['arm']}|insert|bc={r['barcode']}|{r['insert_nt']}nt\n"
            + "\n".join(r["insert"][i : i + 60] for i in range(0, len(r["insert"]), 60))
            + "\n"
            for r in rows
        )
    )
    print(f"\nWrote {table} and {fasta}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
