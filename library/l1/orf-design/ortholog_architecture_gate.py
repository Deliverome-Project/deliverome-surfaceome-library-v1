def failure_end(row: dict) -> str:
    """Where the sequence difference behind a failed gate sits: N, C, internal or mixed."""
    if row["gate"] != "fail":
        return ""
    ends = []
    if row["human_unmatched_n"] or row["ortholog_only_n"]:
        ends.append("N")
    if row["human_unmatched_c"] or row["ortholog_only_c"]:
        ends.append("C")
    if row["human_unmatched_internal"] or row["ortholog_only_internal"]:
        ends.append("internal")
    return "+".join(ends) or "none"


def start_site(
    human: str, ortholog: str, aligner, row: dict, gene_proteins: dict[str, dict]
) -> dict:
    """Methionine aligned to the human start, for a form with an N-terminal extension.

    No window or tolerance: the ortholog residue must be aligned to human residue 1 and be
    a methionine, and the human library protein must start with one. A form that loses the
    SP to the extension gets the plain labels (``exception_candidate`` ...); a form whose
    extension costs no feature gets the same labels prefixed ``n_extension_``.
    """
    out = {
        "start_site": "",
        "start_site_offset": "",
        "start_site_transcript": "",
        "start_site_sha256": "",
    }
    lost = [
        k for k in ("tm_helix_lost", "gpi_anchor_lost", "pfam_domain_lost_with_indel") if row[k]
    ]
    if lost or not row["ortholog_only_n"]:
        return out
    prefix = "" if row["signal_peptide_lost"] else "n_extension_"
    mapping = review.align_map(aligner, human, ortholog)
    j = mapping[0]
    if human[0] != "M" or j is None or j == 0 or ortholog[j] != "M":
        out["start_site"] = prefix + "no_aligned_methionine"
        return out
    trimmed = ortholog[j:]
    sha = review.digest(trimmed)
    out.update(start_site_offset=j, start_site_sha256=sha)
    match = gene_proteins.get(sha)
    if match:
        out.update(
            start_site=prefix + "eligible_transcript", start_site_transcript=match["transcript"]
        )
    else:
        out["start_site"] = prefix + "exception_candidate"
    return out


def write_exceptions(start_rows: list[dict], by_gene: dict, decisions: dict, out_dir: Path) -> None:
    """Registry entries binding each passing restarted form to its native transcript."""
    import audit_ortholog_cds_eligibility as audit

    records = []
    for r in sorted(start_rows, key=lambda r: r["form_id"]):
        if r["gate"] != "pass":
            continue
        entry = by_gene[(r["species"], r["ortholog_ensembl_gene"])][r["sequence_sha256"]]
        codon = int(r["start_site_offset"]) + 1
        decided = decisions.get(r["source_form_id"])
        cds = entry["cds"]
        restarted_cds, restarted_protein = cds[3 * (codon - 1) :], entry["protein"][codon - 1 :]
        if (
            restarted_cds[:3] != "ATG"
            or seqtools.translate(restarted_cds) != restarted_protein + "*"
            or review.digest(restarted_protein) != r["start_site_sha256"]
        ):
            raise ValueError(f"Restarted CDS does not encode the gated protein: {r['form_id']}")
        records.append(
            {
                "exception_id": f"restart-{r['species']}-{r['human_symbol']}-M{codon}",
                "species": r["species"],
                "gene": r["ortholog_ensembl_gene"],
                "transcript_version": entry["transcript_version"],
                "cds_sha256": entry["cds_sha256"],
                "protein_sha256": entry["protein_sha256"],
                "restart_codon": codon,
                "restarted_cds_sha256": review.digest(restarted_cds),
                "restarted_protein_sha256": r["start_site_sha256"],
                "waive_review_reasons": [],
                "decision": "approved",
                "decided_by": decided["decided_by"] if decided else DECIDED_BY,
                "implemented_by": decided["implemented_by"] if decided else IMPLEMENTED_BY,
                "rationale": decided["reason"]
                if decided
                else (
                    f"The native model starts {codon - 1} codons upstream of the methionine "
                    f"aligned to the human {r['human_symbol']} library protein's start, and "
                    "DeepTMHMM v1 calls no signal peptide on it. Restarted there, the protein "
                    "regains the human signal peptide and passes the architecture gate "
                    "(same SP, TM helices, N-terminal side and Pfam domains). This is "
                    "consistent with an upstream-ATG gene-model error; cyno initiation at "
                    "this codon is not independently confirmed."
                ),
                "evidence": [
                    f"ortholog_start_site_gate.tsv:{r['form_id']}",
                    f"DeepTMHMM v1: {r['ortholog_topology_version']}",
                    *[
                        f"{path.relative_to(HERE)} sha256 {review.sha256_file(path)}"
                        for path in prediction_files()
                    ],
                ],
            }
        )
    registry = {"rule_version": EXCEPTION_RULE_VERSION, "exceptions": records}
    audit.validate_registry(registry)
    (out_dir / EXCEPTIONS.name).write_text(json.dumps(registry, indent=2) + "\n")


def prediction_files() -> list[Path]:
    """Committed DeepTMHMM v1 outputs (and run records) for restarted sequences."""
    out = []
    for three in (START_SITE_3LINE, RESTART_3LINE):
        if three.exists():
            out += [three, three.with_name(three.name + ".runtime.json")]
    return out


def rank_fields(entry: dict | None) -> dict:
    if not entry:
        return {"transcript": "", "ensembl_canonical": "", "appris_source": "", "tsl": ""}
    rank = entry.get("rank_evidence") or {}
    if isinstance(rank, str):
        rank = ast.literal_eval(rank)
    annotation = entry.get("annotation") or {}
    return {
        "transcript": entry.get("transcript_version", ""),
        "ensembl_canonical": rank.get("ensembl_canonical", ""),
        "appris_source": rank.get("appris_source", ""),
        "tsl": annotation.get("transcript_support_level", ""),
    }


def pfam_cached(sequences: dict[str, str], hmm: Path, clans: dict, cache: Path) -> dict:
    """Pfam hits per key, cached by sequence hash so reruns skip hmmsearch."""
    store = cache / "pfam39_hits_by_sha256.json"
    known = json.loads(store.read_text()) if store.exists() else {}
    by_sha = {review.digest(s): s for s in sequences.values()}
    todo = {sha: seq for sha, seq in by_sha.items() if sha not in known}
    if todo:
        print(f"hmmsearch on {len(todo)} new sequences", file=sys.stderr)
        known |= review.pfam_scan(todo, hmm, clans)
        store.write_text(json.dumps(known))
    return {k: known[review.digest(s)] for k, s in sequences.items()}


def run(args) -> dict:
    cache = args.cache
    rows, _fixed, extra = review.replay_draw(cache)
    policy, proteins = extra["policy"], extra["proteins"]
    human_cds = json.loads(review.fetch("human_cds", cache).read_text())
    eligible = json.loads(review.fetch("draw_eligible", cache).read_text())
    gpi_genes = {
        r["gene_symbol"]
        for r in review.read_tsv(review.fetch("draw_gpi", cache))
        if r["gpi_anchored"] == "1"
    }
    snapshot = pd.read_parquet(review.fetch("topology_review", cache))
    clans = review.load_clans(review.fetch("pfam_clans", cache))
    drawn = {r["form_id"]: r for r in review.read_tsv(review.PANEL)}

    # Eligible proteins per (species, ortholog gene): protein sha256 -> ledger entry.
    by_gene: dict[tuple[str, str], dict[str, dict]] = defaultdict(dict)
    for species, table in eligible.items():
        for sha, item in table.items():
            for gene, entry in item["by_gene"].items():
                if entry.get("eligibility_status") == "eligible":
                    by_gene[(species, gene)][sha] = entry

    human_seqs, ortho_seqs = {}, {}
    for r in rows:
        seq = proteins[f"{r['species']}|{r['human_symbol']}|{r['picked_acc']}"]
        if review.digest(seq) != r["sequence_sha256"]:
            raise ValueError(f"Representative protein checksum mismatch: {r['form_id']}")
        ortho_seqs[r["form_id"]] = seq
        hk = f"human|{r['human_symbol']}"
        if hk not in human_seqs:
            h = seqtools.translate(human_cds[f"lib:{r['human_symbol']}"]["cds"]).rstrip("*")
            if review.digest(h) != r["human_reference_sha256"]:
                raise ValueError(f"Human library protein checksum mismatch: {r['human_symbol']}")
            human_seqs[hk] = h

    topo = review.topology_rows(human_seqs, "human", snapshot)
    for species in ("mouse", "cyno"):
        sub = {r["form_id"]: ortho_seqs[r["form_id"]] for r in rows if r["species"] == species}
        topo |= review.topology_rows(sub, species, snapshot)
    pfam = pfam_cached({**human_seqs, **ortho_seqs}, args.pfam_hmm, clans, cache)

    aligner = review.make_aligner()
    out = []
    for r in rows:
        hk, fid = f"human|{r['human_symbol']}", r["form_id"]
        h, o = human_seqs[hk], ortho_seqs[fid]
        evidence = review.compare(
            h,
            o,
            topo[hk],
            topo[fid],
            pfam[hk],
            pfam[fid],
            r["human_symbol"] in gpi_genes,
            r["anchor_call"],
            aligner,
        )
        rule, why = review.recommend(evidence)
        row = {
            **r,
            **evidence,
            "rule_recommendation": rule,
            "rule_basis": why,
            "gate": GATE[rule],
            "drawn_in_review_panel": fid in drawn,
            "human_topology_version": topo[hk]["topology_version"],
            "ortholog_topology_version": topo[fid]["topology_version"],
        }
        row["failure_end"] = failure_end(row)
        gene_proteins = by_gene[(r["species"], r["ortholog_ensembl_gene"])]
        row |= start_site(h, o, aligner, row, gene_proteins)
        others = {
            sha: e["protein"] for sha, e in gene_proteins.items() if sha != r["sequence_sha256"]
        }
        row["other_eligible_proteins"] = len(others)
        row["other_eligible_with_v1_row"] = ""
        if row["gate"] != "pass" and others:
            found = topology.resolve(
                others,
                tool=topology.TOOL_V1,
                cohorts=topology.cohorts_for_species(r["species"]),
                snapshot=snapshot,
            )
            row["other_eligible_with_v1_row"] = int(found["found"].sum())
        ranks = rank_fields(gene_proteins.get(r["sequence_sha256"]))
        row |= {
            "transcript": ranks["transcript"],
            "ensembl_canonical": ranks["ensembl_canonical"],
            "appris_source": ranks["appris_source"],
            "transcript_support_level": ranks["tsl"],
        }
        out.append(row)

    # Self-check against the committed review of the 200 drawn forms.
    recorded = {r["form_id"]: r["rule_recommendation"] for r in review.read_tsv(REVIEW_TABLE)}
    mismatched = [
        r["form_id"]
        for r in out
        if r["drawn_in_review_panel"] and recorded[r["form_id"]] != r["rule_recommendation"]
    ]
    if mismatched or sum(r["drawn_in_review_panel"] for r in out) != len(recorded):
        raise ValueError(f"Gate disagrees with the committed review for {mismatched}")

    out.sort(key=lambda r: (r["species"], r["band"], r["topology_class"], r["human_symbol"]))
    review.write(args.out_dir / "ortholog_architecture_gate.tsv", out, COLUMNS)

    # Start-site candidates: write the sequences to predict, and gate them once predicted.
    decisions = (
        {d["form_id"]: d for d in review.read_tsv(RESTART_DECISIONS)}
        if RESTART_DECISIONS.exists()
        else {}
    )
    by_form = {r["form_id"]: r for r in out}
    for form_id, d in decisions.items():
        r = by_form.get(form_id)
        if r is None or r["start_site"] != "n_extension_exception_candidate":
            raise ValueError(
                f"Restart decision for a form without an aligned methionine: {form_id}"
            )
        if d["decision"] != "restart":
            raise ValueError(f"Unknown restart decision for {form_id}: {d['decision']}")
    sp_candidates = [r for r in out if r["start_site"] == "exception_candidate"]
    decided = [by_form[f] for f in sorted(decisions)]
    candidates = sp_candidates + decided
    trimmed = {
        r["start_site_sha256"]: ortho_seqs[r["form_id"]][int(r["start_site_offset"]) :]
        for r in candidates
    }

    def fasta(rows: list[dict]) -> str:
        return "".join(
            f">{r['species']}_{r['human_symbol']}_M{int(r['start_site_offset']) + 1}\n"
            f"{trimmed[r['start_site_sha256']]}\n"
            for r in rows
        )

    START_SITE_DIR.mkdir(exist_ok=True)
    if not START_SITE_FASTA.exists() or START_SITE_FASTA.read_text() != fasta(sp_candidates):
        START_SITE_FASTA.write_text(fasta(sp_candidates))

    # Exact-sequence v1 rows: committed run outputs first, then the pinned snapshot.
    predicted: dict[str, dict] = {}
    for three in (START_SITE_3LINE, RESTART_3LINE):
        if three.exists():
            predicted |= read_3line(three)
    for r in candidates:
        sha = r["start_site_sha256"]
        if sha in predicted:
            continue
        found = topology.resolve(
            {sha: trimmed[sha]},
            tool=topology.TOOL_V1,
            cohorts=topology.cohorts_for_species(r["species"]),
            snapshot=snapshot,
        )
        if found["found"].iloc[0]:
            predicted[sha] = found.iloc[0].to_dict()
    unpredicted = [r for r in decided if r["start_site_sha256"] not in predicted]
    if unpredicted:
        RESTART_FASTA.write_text(fasta(unpredicted))
    if START_SITE_3LINE.exists() and any(
        r["start_site_sha256"] not in predicted for r in sp_candidates
    ):
        raise ValueError("Start-site predictions do not cover the candidate FASTA")

    start_rows = []
    gated = [r for r in candidates if r["start_site_sha256"] in predicted]
    trimmed_ids = {f"{r['form_id']}:M{int(r['start_site_offset']) + 1}": r for r in gated}
    pfam_trim = pfam_cached(
        {k: trimmed[r["start_site_sha256"]] for k, r in trimmed_ids.items()},
        args.pfam_hmm,
        clans,
        cache,
    )
    for key, r in trimmed_ids.items():
        hk = f"human|{r['human_symbol']}"
        sha = r["start_site_sha256"]
        evidence = review.compare(
            human_seqs[hk],
            trimmed[sha],
            topo[hk],
            predicted[sha],
            pfam[hk],
            pfam_trim[key],
            r["human_symbol"] in gpi_genes,
            r["anchor_call"],
            aligner,
        )
        rule, why = review.recommend(evidence)
        start_rows.append(
            {
                **r,
                **evidence,
                "form_id": key,
                "source_form_id": r["form_id"],
                "restart_trigger": "decision" if r["form_id"] in decisions else "sp_lost",
                "rule_recommendation": rule,
                "rule_basis": why,
                "gate": GATE[rule],
                "ortholog_topology_version": predicted[sha]["topology_version"],
            }
        )
    if start_rows:
        review.write(args.out_dir / "ortholog_start_site_gate.tsv", start_rows, START_SITE_COLUMNS)
        write_exceptions(start_rows, by_gene, decisions, args.out_dir)

    feasibility = []
    for key, quota in sorted(policy["quotas"].items()):
        species, band, cls = key.split("|")
        sub = [
            r
            for r in out
            if (r["species"], r["band"], r["topology_class"]) == (species, band, cls)
            and r["sequence_sha256"] != r["human_reference_sha256"]
        ]
        gates = Counter(r["gate"] for r in sub)
        rescues = sum(r["start_site"] == "eligible_transcript" for r in sub)
        feasibility.append(
            {
                "species": species,
                "band": band,
                "topology_class": cls,
                "quota": quota,
                "sampleable": len(sub),
                "pass": gates["pass"],
                "review": gates["review"],
                "fail": gates["fail"],
                "fail_fraction": round(gates["fail"] / len(sub), 4) if sub else "",
                "start_site_eligible_transcript": rescues,
                "quota_met_by_pass": gates["pass"] >= quota,
            }
        )
    review.write(
        args.out_dir / "ortholog_architecture_gate_feasibility.tsv",
        feasibility,
        list(feasibility[0]),
    )

    def tally(key):
        return dict(sorted(Counter(key(r) for r in out).items()))

    summary = {
        "rule_version": RULE_VERSION,
        "review_rule_version": review.RULE_VERSION,
        "sampleable_representatives": len(out),
        "gate": tally(lambda r: r["gate"]),
        "gate_by_species_band": {
            f"{s}|{b}": dict(
                sorted(
                    Counter(r["gate"] for r in out if (r["species"], r["band"]) == (s, b)).items()
                )
            )
            for s in ("mouse", "cyno")
            for b in ("near", "diverged")
        },
        "fail_by_flag": {
            f: sum(bool(r[f]) for r in out if r["gate"] == "fail")
            for f in review.ARCHITECTURE_FLAGS
        },
        "fail_by_end": tally(lambda r: r["failure_end"] or "not_failed"),
        "start_site": tally(lambda r: r["start_site"] or "not_applicable"),
        "start_site_predicted": len(start_rows),
        "restart_decisions": len(decisions),
        "restart_decisions_awaiting_prediction": sorted(r["form_id"] for r in unpredicted),
        "start_site_gate": dict(sorted(Counter(r["gate"] for r in start_rows).items())),
        "failed_with_other_eligible_proteins": sum(
            r["gate"] == "fail" and r["other_eligible_proteins"] > 0 for r in out
        ),
        "other_eligible_proteins_of_failed_forms": sum(
            r["other_eligible_proteins"] for r in out if r["gate"] == "fail"
        ),
        "of_which_with_v1_row": sum(
            r["other_eligible_with_v1_row"] or 0 for r in out if r["gate"] == "fail"
        ),
        "strata_where_pass_meets_quota": sum(f["quota_met_by_pass"] for f in feasibility),
        "strata": len(feasibility),
        "drawn_forms_match_committed_review": True,
    }
    (args.out_dir / "ortholog_architecture_gate_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n"
    )
    plot(feasibility, args.out_dir)
    return summary


def plot(feasibility: list[dict], out_dir: Path) -> None:
    """Share of each stratum's sampleable forms that pass, need review or fail the gate."""
    import matplotlib.pyplot as plt

    from deliverome_analysis.plotting import get_color, save_figure, setup_plotting_style

    setup_plotting_style()
    order = sorted(
        feasibility,
        key=lambda f: (f["species"] != "mouse", f["band"] != "near", f["topology_class"]),
    )
    labels = [
        f"{f['species']} {f['band']} {f['topology_class']} (n={f['sampleable']}, quota {f['quota']})"
        for f in order
    ]
    colors = {
        "pass": get_color("neutral"),
        "review": get_color("accent"),
        "fail": get_color("primary"),
    }
    fig, ax = plt.subplots(figsize=(11, 9))
    y = list(range(len(order)))
    left = [0.0] * len(order)
    for gate in ("pass", "review", "fail"):
        values = [f[gate] / f["sampleable"] for f in order]
        ax.barh(y, values, left=left, color=colors[gate], label=gate, height=0.7)
        left = [a + b for a, b in zip(left, values, strict=True)]
    ax.set_yticks(y, labels, fontsize=12)
    ax.invert_yaxis()
    ax.set_xlim(0, 1)
    ax.set_xlabel("Fraction of sampleable representatives")
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=3, frameon=False)
    save_figure(fig, out_dir / "figures" / "ortholog_architecture_gate")
    plt.close(fig)


