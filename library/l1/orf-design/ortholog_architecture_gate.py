def read_3line(path: Path) -> dict[str, dict]:
    """DeepTMHMM 3-line output keyed by sequence sha256: label, sequence, per-residue string."""
    lines = [line.rstrip("\n") for line in path.read_text().splitlines() if line.strip()]
    out = {}
    for i in range(0, len(lines), 3):
        header, seq, topo = lines[i : i + 3]
        label = header.split("|")[-1].strip()
        if len(seq) != len(topo) or set(topo) - set("SIOMB"):
            raise ValueError(f"Malformed DeepTMHMM v1 record: {header}")
        out[review.digest(seq)] = {
            "per_residue_topology": topo,
            "signal_peptide_length": len(topo) - len(topo.lstrip("S")),
            "deeptmhmm_label": label,
            "topology_version": f"{topology.TOOL_V1}:{path.name}",
        }
    return out


