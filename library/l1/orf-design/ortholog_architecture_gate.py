"""Proposed ortholog draw update: an architecture gate and a start-site rule, on the full pool.

The current draw (``ORTHOLOG_CDS_POLICY.md``) admits a form on coding-sequence evidence,
ranks a gene's eligible proteins by correspondence to the human library protein, and draws
from fixed quotas. Domain and topology are only reviewed afterwards
(``ORTHOLOG_CORRESPONDENCE_REVIEW.md``). This script asks what moving that review in front
of the draw would do. It applies the review's own rule to every sampleable representative
(3,643 gene-species forms, not only the 200 drawn ones):

* **gate** -- ``pass`` (the review's ``keep``), ``review`` (``ask``) or ``fail``
  (``replace``: a human TM helix, signal peptide or GPI anchor, or a Pfam domain whose span
  carries an indel, has no counterpart). Same evidence, same categorical rule, no cutoff.
* **start-site rule** -- for a form whose only signal-peptide problem is an N-terminal
  extension: when the ortholog has a methionine at the residue aligned to the human
  library protein's start methionine, the form ``trimmed`` to that methionine is the
  candidate the policy should use. It is ``eligible_transcript`` when another
  CDS-eligible protein of the same ortholog gene is exactly that sequence, and
  ``exception_candidate`` otherwise (a checksum-bound entry in the policy's exception
  registry, which needs its own DeepTMHMM v1 prediction before it can be gated).
* **feasibility** -- per stratum (species x band x human topology class), how many
  sampleable forms pass, against the quota.

Self-check: the 200 drawn forms must get exactly the rule results recorded in
``ortholog_correspondence_review.tsv``.

Analysis only: no manifest, panel, construct table, pipeline, D1 record or existing S3
key changes. The only new predictions are DeepTMHMM v1 for the 15 start-site candidates
(see START_SITE_3LINE). Proposed by the Claude Code session
ortholog-correspondence-review on 2026-11-11 at Becca Carlson's request ("Yes, draft it");
adopting any of it is Becca's decision.

    uv run --locked --group modal --group domains python \
        library/l1/orf-design/ortholog_architecture_gate.py
"""

