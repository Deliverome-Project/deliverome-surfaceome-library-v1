"""Re-key the rung arm tables and their decision inputs after a renumber, through design ids.

``renumber_library_members.py --write`` re-keys the current-library records it lists. The rung
arm tables (``constructs_l1_<rung>.tsv`` / ``.fasta``) and the decision tables their builders
read carry member ids too, and each builder asserts its inputs and outputs agree, so after a
renumber they must move together. This script maps every whole ``l1-mNNNN`` token in those files
from the previous numbering to the current one: previous member id -> design id (the mapping
at ``--from``, a git ref) -> current member id (the committed ``l1_member_renumbering.tsv``).
Nothing but member-id tokens changes; each builder's ``--check`` then confirms its table
rebuilds byte for byte.

Run on 2026-11-14 for the final regeneration (ordered-length numbering), from ``main`` at
cdb78068. Requested by the coordinator; implemented by the Claude Code session
l1-reviewer-package.

    uv run --locked python rekey_rung_tables.py --from cdb78068
"""

from __future__ import annotations

import argparse
import csv
import io
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
REL = HERE.relative_to(REPO).as_posix()
MAPPING = "l1_member_renumbering.tsv"
# Do not match archived S3 filenames like ``.../2026-11-12/l1-m0008.type3.pdb``.
MEMBER = re.compile(r"(?<!/)\bl1-m\d{4}\b(?!\.)")
#: The rung builders' inputs and outputs that carry member ids. The C-terminal review and
#: decisions are regenerated by their own scripts, not re-keyed here.
FILES = (
    "reviewer-package/nterm/nterm_decisions.tsv",
    "nterm_res1_multipass.tsv",
    "type3_nterm_calls.tsv",
    "type3_nterm_features.tsv",
    "type3_decisions.tsv",
    "constructs_l1_nterm.tsv",
    "constructs_l1_nterm.fasta",
    "constructs_l1_multipass.tsv",
    "constructs_l1_multipass.fasta",
    "multipass_arms_mature.fasta",
    "constructs_l1_type3.tsv",
    "constructs_l1_type3.fasta",
    "constructs_l1_type3_proteins.tsv",
    "constructs_l1_type3_proteins.fasta",
)


#: The N-terminal package's working tables. Its scripts join them to each other and to
#: ``nterm_decisions.tsv`` on ``candidate_id``, so they must share one numbering with it. Each
#: carries ``design_id``, so its member ids are re-keyed through that column, which works
#: whichever earlier numbering a table was written in (2026-11-14, after a join between the
#: re-keyed decisions and the dated census named the wrong protein).
DESIGN_KEYED = (
    "reviewer-package/nterm/nterm_build_options.tsv",
    "reviewer-package/nterm/nterm_members.tsv",
    "reviewer-package/nterm/nterm_positions.tsv",
    "reviewer-package/nterm/nterm_site_picks.tsv",
    "reviewer-package/nterm/overnight_inputs.tsv",
    "reviewer-package/nterm/overnight_proposals.tsv",
    "reviewer-package/nterm/overnight_verdicts.tsv",
    "reviewer-package/nterm/propeptide_check.tsv",
    "reviewer-package/nterm/refold_batches/nterm_held_2026_11_12.tsv",
    "reviewer-package/nterm/refold_requests.tsv",
    "reviewer-package/nterm/round2_inputs.tsv",
    "reviewer-package/nterm/signalp_inputs.tsv",
    "reviewer-package/nterm/signalp_run_verdicts.tsv",
    "reviewer-package/nterm/sp_disagree_review.tsv",
    "reviewer-package/nterm/hold_review.tsv",
    "reviewer-package/nterm/weak_sp.tsv",
)
ID_COLUMNS = ("candidate_id", "member_id")


def rekey_by_design(now: dict[str, str]) -> None:
    """Set each row's member-id columns from its design id (rows of retired designs keep theirs)."""
    for name in DESIGN_KEYED:
        path = HERE / name
        if not path.exists():
            continue
        text = path.read_text()
        reader = csv.DictReader(io.StringIO(text), delimiter="\t")
        cols = list(reader.fieldnames or [])
        rows = list(reader)
        if not rows or "design_id" not in cols:
            continue
        for r in rows:
            for c in ID_COLUMNS:
                if c in r and r["design_id"] in now and MEMBER.fullmatch(r[c] or ""):
                    r[c] = now[r["design_id"]]
        buf = io.StringIO()
        w = csv.DictWriter(buf, cols, delimiter="\t", lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
        if buf.getvalue() != text:
            path.write_text(buf.getvalue())
            print(f"re-keyed by design id {name}")


def mapping(text: str) -> dict[str, str]:
    """Design id -> member id."""
    return {
        r["design_id"]: r["candidate_id"] for r in csv.DictReader(io.StringIO(text), delimiter="\t")
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--from", dest="ref", required=True, help="git ref of the previous numbering")
    args = ap.parse_args(argv)
    from deliverome_analysis.provenance import read_pinned_text

    before = mapping(read_pinned_text(args.ref, f"{REL}/{MAPPING}", repo=REPO))
    now = mapping((HERE / MAPPING).read_text())
    rekey_by_design(now)
    old_to_new = {m: now[d] for d, m in before.items() if d in now}
    for name in FILES:
        path = HERE / name
        text = path.read_text()
        unknown = sorted({t for t in MEMBER.findall(text) if t not in old_to_new})
        if unknown:
            raise SystemExit(f"{name}: member ids not in the {args.ref} mapping: {unknown[:5]}")
        new = MEMBER.sub(lambda m: old_to_new[m.group(0)], text)
        if new != text:
            path.write_text(new)
            print(f"re-keyed {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
