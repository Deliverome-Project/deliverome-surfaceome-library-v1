#!/usr/bin/env python3
"""Coverage of known-target reference sets by the CURRENT surface library.

For each reference set — SurfaceBench "yes", ViralZone human entry receptors,
high-confidence ADC targets (the curated positive-control list, NOT adcdb), and
TCE targets — report how many are captured by the current library
(library_membership.tsv, regenerated by final_library.py) and categorise every
miss by why it was excluded. Emits a grouped coverage barplot + a per-gene TSV.

Provenance: reads library_membership.tsv (final_library.py) + the ref sets in
external/accessible_surfaceome_refs/. Run: uv run python reference_coverage.py
"""
# ruff: noqa: E402

import csv
import json
import os
import re

import build_library as B
import final_library as F  # single source of truth for gates + membership
import matplotlib.pyplot as plt
import numpy as np

from deliverome_analysis.core.plotting import CATEGORICAL_PALETTE, save_figure, setup_plotting_style

HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(HERE, "external", "accessible_surfaceome_refs")
setup_plotting_style()

# ---- current library + universe/cohort maps ----
lib = {
    r["gene"]: r["tier"]
    for r in csv.DictReader(open(os.path.join(HERE, "library_membership.tsv")), delimiter="\t")
}
cat = json.load(open(os.path.join(HERE, "catalog_rows.json")))
universe = {r["symbol"] for r in cat}
uni2sym = {r["uniprot"]: r["symbol"] for r in cat if r.get("uniprot")}
recs = {r["gene"]: r for r in F.recs}  # deep-dived cohort (5,130)

_UNIPROT = re.compile(r"[OPQ][0-9][A-Z0-9]{3}[0-9]|[A-NR-Z][0-9]([A-Z][A-Z0-9]{2}[0-9]){1,2}")


def miss_reason(sym):
    """Why is this reference gene NOT in the library?"""
    if sym not in universe:
        return "not in surfaceome universe"
    r = recs.get(sym)
    if r is None:
        return "in universe, not deep-dived"
    f = r["filters"]
    if not (B.passes_canonical(f) or B.passes_likely(f)):
        return "below-Likely (membership/evidence)"
    if not F.orf_ok(r):
        return "oversized (>5 kb ORF)"
    fails = []
    if f.get("surface_accessibility") == "no":
        fails.append("accessibility=no")
    if f.get("surface_specificity") not in ("surface_dominant", "mixed"):
        fails.append("mostly_intracellular")
    if not F.anchored(r):
        fails.append("not anchored")
    if not F.coreceptor_ok(sym, f):
        fails.append("co-receptor")
    if not F.expr_ok(sym, f):
        fails.append("low expression")
    if f.get("surface_call_reason") in B.NONSURFACE_REASONS:
        fails.append(f"reason={f.get('surface_call_reason')}")
    if not F.ecd_ok(r):
        fails.append("ECD<30")
    return "filtered: " + ",".join(fails) if fails else "filtered (other)"


# ---- load the four reference sets as {gene set} ----
def load_symbol_col(path, col, delim="\t", where=None):
    out = set()
    for row in csv.DictReader(open(path), delimiter=delim):
        if where and not where(row):
            continue
        g = (row.get(col) or "").strip()
        if g:
            out.add(g)
    return out


sb = load_symbol_col(
    os.path.join(REF, "triage_benchmark_v1.tsv"),
    "gene_symbol",
    where=lambda r: r.get("ground_truth_verdict") == "yes",
)
adc = load_symbol_col(os.path.join(REF, "positive_control_ADC.tsv"), "hgnc_symbol")
tce = load_symbol_col(os.path.join(REF, "positive_control_TCE.tsv"), "hgnc_symbol")

# ViralZone: resolve UniProt accessions in the messy "Receptor" field -> HGNC symbol.
# Non-protein receptors (gangliosides/CHEBI, heparan sulfate) carry no UniProt acc
# and are excluded — they are not targetable surface *proteins*.
vz = set()
vz_nonprotein = 0
for row in csv.DictReader(open(os.path.join(REF, "viralzone_human_entry_receptors.csv"))):
    val = row.get("Receptor") or ""
    accs = [m.group(0) for m in _UNIPROT.finditer(val)]
    syms = {uni2sym.get(a) for a in accs} - {None}
    if not syms:
        vz_nonprotein += 1
        continue
    vz |= syms

SETS = [
    ("SurfaceBench = yes", sb),
    ("ViralZone receptors", vz),
    ("ADC (high-conf)", adc),
    ("TCE targets", tce),
]

# ---- coverage + miss categorisation ----
rows_out = []
summary = []
for name, gs in SETS:
    captured = sorted(g for g in gs if g in lib)
    missed = sorted(g for g in gs if g not in lib)
    pct = 100 * len(captured) / len(gs) if gs else 0
    summary.append((name, len(gs), len(captured), len(missed), pct))
    for g in captured:
        rows_out.append(
            dict(reference_set=name, gene=g, in_library="yes", tier=lib[g], miss_reason="")
        )
    for g in missed:
        rows_out.append(
            dict(reference_set=name, gene=g, in_library="no", tier="", miss_reason=miss_reason(g))
        )

with open(os.path.join(HERE, "reference_coverage.tsv"), "w", newline="") as fh:
    w = csv.DictWriter(
        fh,
        fieldnames=["reference_set", "gene", "in_library", "tier", "miss_reason"],
        delimiter="\t",
    )
    w.writeheader()
    w.writerows(rows_out)

print("=" * 74)
print(f"{'reference set':22}{'total':>7}{'in library':>12}{'missed':>8}{'coverage':>10}")
for name, tot, cap, miss, pct in summary:
    print(f"{name:22}{tot:>7}{cap:>12}{miss:>8}{pct:>9.0f}%")
print(
    f"\n(ViralZone: {vz_nonprotein} non-protein receptors — gangliosides/CHEBI/HSPG — excluded from the denominator)"
)
print("\n-- missed genes by set (with reason) --")
from collections import Counter

for name, gs in SETS:
    missed = sorted(g for g in gs if g not in lib)
    print(f"\n{name}: {len(missed)} missed")
    reasons = Counter(miss_reason(g) for g in missed)
    for g in missed:
        print(f"   {g:12} {miss_reason(g)}")

# ---- figure: horizontal stacked coverage bars (captured + missed) ----
labels = [s[0] for s in summary]
caps = [s[2] for s in summary]
misses = [s[3] for s in summary]
pcts = [s[4] for s in summary]
y = np.arange(len(labels))[::-1]  # top-to-bottom in list order

fig, ax = plt.subplots(figsize=(9.5, 4.4))
ax.barh(y, caps, color=CATEGORICAL_PALETTE[1], label="in library")
ax.barh(y, misses, left=caps, color="0.75", label="missed")
for yi, (cap, miss, pct) in zip(y, zip(caps, misses, pcts, strict=False), strict=False):
    tot = cap + miss
    ax.text(
        tot + max(caps + misses) * 0.01, yi, f"{cap}/{tot}  ({pct:.0f}%)", va="center", fontsize=9
    )
ax.set_yticks(y)
ax.set_yticklabels(labels)
ax.set_xlabel("genes in reference set")
ax.set_xlim(0, max(c + m for c, m in zip(caps, misses, strict=False)) * 1.22)
ax.legend(loc="lower right", frameon=False)
save_figure(fig, "reference_set_coverage", output_dir=os.path.join(HERE, "figures"))
print("\nwrote reference_set_coverage + reference_coverage.tsv")
