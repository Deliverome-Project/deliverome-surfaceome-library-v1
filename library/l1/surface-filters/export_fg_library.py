#!/usr/bin/env python3
"""Regenerate the FG surface-protein library membership, publish it to S3, and
optionally refresh the accessible-surfaceome viewer's committed copy — one
command to run after the library changes.

  # regenerate + upload to S3 (source of truth) + refresh the viewer copy:
  uv run python export_fg_library.py \
      --viewer-path ../../../../accessible-surfaceome/viewer/public/data/fg-library.json

  # regenerate + upload only (no viewer copy):
  uv run python export_fg_library.py

  # dry run — regenerate locally, no S3, write viewer copy to a temp path:
  uv run python export_fg_library.py --no-s3 --viewer-path /tmp/fg-library.json

Steps:
  1. Re-run final_library.py (importing it recomputes the library and writes
     library_membership.tsv + tier_counts.json), then build the rich membership
     (gene -> tier + surface-competent isoform ids + orthologs).
  2. Upload library_membership.tsv, fg_library_membership.json, tier_counts.json
     to s3://deliverome-processed/sprint1/s1e3-surface-library-filters/  — the
     source of truth the viewer's committed copy is generated from.
  3. If --viewer-path is given, write the viewer-shaped fg-library.json there
     ({n_genes, genes}, indent=2 — matches the committed file, so a re-run diffs
     only on real membership changes). Commit that file in the viewer repo.

Lineage: final_library.py (here) -> S3 (archive/source of truth) -> committed
viewer copy (accessible-surfaceome viewer/public/data/fg-library.json).
"""

import argparse
import csv
import json
import os

import build_library as B
import final_library as F  # importing recomputes the library + writes library_membership.tsv / tier_counts.json

HERE = os.path.dirname(os.path.abspath(__file__))
S3_PREFIX = "l1/surface-filters"
NOTE = (
    "Deliverome FG surface-protein library membership (s1e3). gene -> tier "
    "(T1/T2/T3 graded, LL low-lit/UniProt, SV screen-validated, OE overexpression-"
    "rescue), plus surface-competent isoform ids and orthologs per gene. "
    "Generated by export_fg_library.py from final_library.py."
)


def cohort_provenance() -> dict:
    """Describe the cohort snapshot this export was actually built from.

    This used to be a hardcoded claim that the export ran "on the live-D1
    cohort". It could not: ``final_library`` reads ``cohort.jsonl`` off disk,
    and ``fetch_cohort.py``'s default resume mode never refreshes a record it
    already has — so the export could assert freshness while sitting on an
    arbitrarily old snapshot, with no way for a consumer to tell.

    Now we report what the sidecar says, and say plainly when we don't know.
    """
    path = os.path.join(HERE, "cohort_provenance.json")
    if not os.path.exists(path):
        return {
            "status": "unknown",
            "detail": (
                "No cohort_provenance.json — the cohort predates provenance "
                "tracking, or was assembled by hand. Re-run "
                "`python3 fetch_cohort.py --refresh` to establish it."
            ),
        }
    with open(path) as fh:
        prov = json.load(fh)
    prov["status"] = "current" if prov.get("stale_records", 0) == 0 else "partially_stale"
    if prov["status"] == "partially_stale":
        prov["detail"] = (
            f"{prov['stale_records']} of {prov.get('total_records')} records were "
            f"carried over from an earlier fetch and may not reflect current D1 "
            f"state. Re-run `python3 fetch_cohort.py --refresh` for a clean snapshot."
        )
    return prov


def _surf_iso_ids(r):
    sub = r["filters"].get("subcategory")
    return [
        it.get("isoform_id")
        for it in r.get("isoforms", [])
        if it.get("isoform_id")
        and B.topology_status(
            it.get("tm_helix_count"),
            it.get("signal_peptide_length"),
            it.get("per_residue_topology"),
            sub,
        )
        == "surface"
    ]


def _surf_orth(r):
    sub = r["filters"].get("subcategory")
    out = []
    for sp in ("mouse", "cyno"):
        for o in r.get("orthologs", {}).get(sp, []):
            if (o.get("ecd_pct_identity_to_human_canonical") or 0) < F.ORTHO_ECD_MIN:
                continue
            if o.get("ortholog_symbol") and (
                B.topology_status(
                    o.get("tm_helix_count"),
                    None,
                    o.get("per_residue_topology"),
                    sub,
                    o.get("deeptmhmm_label"),
                )
                == "surface"
            ):
                out.append({"symbol": o.get("ortholog_symbol"), "species": sp})
    return out


def build_membership() -> dict:
    """gene -> {tier, surface_isoform_ids, surface_orthologs}, matching the
    surface-isoform / surface-ortholog rules in final_library.py."""
    lib = {
        r["gene"]: r["tier"]
        for r in csv.DictReader(open(os.path.join(HERE, "library_membership.tsv")), delimiter="\t")
    }
    recs = {r["gene"]: r for r in F.recs}
    genes = {}
    for g in sorted(lib):
        r = recs.get(g)
        genes[g] = {
            "tier": lib[g],
            "surface_isoform_ids": _surf_iso_ids(r) if r else [],
            "surface_orthologs": _surf_orth(r) if r else [],
        }
    return genes


def build_oversized() -> dict:
    """gene -> {tier, orf_kb, surface_isoform_ids, surface_orthologs} for the
    OVERSIZED genes: those that clear every library gate EXCEPT the ~5 kb ORF
    cap (final_library._passes_except_orf and not orf_ok). Truncation
    candidates — exported as a SEPARATE block (not merged into `genes`) so the
    viewer can show them as in-library with an "Oversized" chip WITHOUT
    inflating the core library count."""
    out = {}
    for r in F.recs:
        if F._passes_except_orf(r) and not F.orf_ok(r):
            nt = F.orf_nt(r)
            out[r["gene"]] = {
                "tier": F.tier(r),
                "orf_kb": round(nt / 1000, 1) if nt else None,
                "surface_isoform_ids": _surf_iso_ids(r),
                "surface_orthologs": _surf_orth(r),
            }
    return {g: out[g] for g in sorted(out)}


def main() -> None:
    ap = argparse.ArgumentParser(description="Export the FG library membership to S3 + the viewer.")
    ap.add_argument(
        "--viewer-path",
        help="write the viewer-shaped fg-library.json here (committed in the viewer repo)",
    )
    ap.add_argument(
        "--no-s3", action="store_true", help="skip the S3 upload (local regenerate only)"
    )
    args = ap.parse_args()

    genes = build_membership()
    oversized = build_oversized()
    full = {
        "note": NOTE,
        "cohort_provenance": cohort_provenance(),
        "n_genes": len(genes),
        "genes": genes,
        "n_oversized": len(oversized),
        "oversized": oversized,
    }
    local_json = os.path.join(HERE, "fg_library_membership.json")
    with open(local_json, "w") as fh:
        json.dump(full, fh, indent=2)
        fh.write("\n")
    print(
        f"\nregenerated fg_library_membership.json: {len(genes)} genes "
        f"+ {len(oversized)} oversized (truncation candidates, separate block)"
    )

    if not args.no_s3:
        from deliverome_analysis.core.s3 import processed

        for fname, ctype in (
            ("library_membership.tsv", "text/tab-separated-values"),
            ("fg_library_membership.json", "application/json"),
            ("tier_counts.json", "application/json"),
        ):
            processed.upload(os.path.join(HERE, fname), f"{S3_PREFIX}/{fname}", content_type=ctype)
            print(f"uploaded  s3://deliverome-processed/{S3_PREFIX}/{fname}")

    if args.viewer_path:
        # Viewer schema: {n_genes, genes} (no `note`), indent=2 — byte-compatible
        # with the committed file so re-runs diff only on real membership changes.
        os.makedirs(os.path.dirname(os.path.abspath(args.viewer_path)), exist_ok=True)
        with open(args.viewer_path, "w") as fh:
            json.dump(
                {
                    "n_genes": len(genes),
                    "genes": genes,
                    "n_oversized": len(oversized),
                    "oversized": oversized,
                },
                fh,
                indent=2,
            )
            fh.write("\n")
        print(f"wrote viewer copy: {args.viewer_path}")


if __name__ == "__main__":
    main()
